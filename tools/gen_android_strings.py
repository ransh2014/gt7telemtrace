"""gen_android_strings.py -- write android/app/src/main/res/values/strings.xml from src/gt7telem/labels.py.

labels.py is the single source of UI wording; this turns it into Android string resources (name = constant name
in lower case, ``{x}`` placeholders -> ``%1$s``...). Run it after editing labels.py:

    python tools/gen_android_strings.py

tests/test_android_parity.py fails if strings.xml is out of date or Android code stops using a label.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))
OUT = REPO / "android" / "app" / "src" / "main" / "res" / "values" / "strings.xml"


def to_android(text: str) -> str:
    n = [0]

    def ph(_m):
        n[0] += 1
        return f"%{n[0]}$s"

    t = re.sub(r"\{[a-z_]+\}", ph, text)
    t = t.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = t.replace('"', '\\"')
    # wrapped in double quotes so aapt keeps runs of spaces (e.g. "Launch  ->") exactly as on the desktop
    return '"' + t + '"'


def render() -> str:
    from gt7telem import labels
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- GENERATED by tools/gen_android_strings.py from src/gt7telem/labels.py - do not edit by hand. -->",
             "<resources>", '    <string name="app_name" translatable="false">TRACE</string>']
    for k, v in labels.shared().items():
        lines.append(f'    <string name="{k.lower()}" translatable="false">{to_android(v)}</string>')
    for arr, tabs in (("lap_chart_tabs", labels.LAP_CHART_TABS), ("race_chart_tabs", labels.RACE_CHART_TABS)):
        lines.append(f'    <string-array name="{arr}" translatable="false">')
        lines += [f"        <item>{to_android(t)}</item>" for t in tabs]
        lines.append("    </string-array>")
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
