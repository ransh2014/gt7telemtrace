def share_case(meta, colmap):
    n = len(next(iter(colmap.values())))
    lap = dict(meta, samples=[{k: v[i] for k, v in colmap.items()} for i in range(n)])
    prob = sharelink.sharing_problem(lap)
    out = {"meta": meta, "problem": _SHARE_CODES[prob] if prob else None, "key": sharelink.lap_key(lap),
           "cols": {k: [None if (x is None or not math.isfinite(x)) else x for x in v] for k, v in colmap.items()}}
    if not prob:
        out["json"] = sharelink.payload_json(sharelink.build_payload(lap)).decode("ascii")
        out["n"] = sharelink.build_payload(lap)["n"]
    return out


