def slow_lap(df, regions, drop=0.18, brake_shift=0.0, thr_shift=0.0):
    d = df.copy()
    pos = d["track_position"].to_numpy(float)
    spd = d["speed_kmh"].to_numpy(float)
    f = np.ones(len(d))
    for a, b in regions:
        f[(pos >= a) & (pos <= b)] = 1 - drop
    spd2 = spd * f
    t = d["t"].to_numpy(float)
    dts = np.diff(t, prepend=t[0])
    d["t"] = t[0] + np.cumsum(dts * spd / np.maximum(spd2, 1.0))
    d["speed_kmh"] = spd2
    if brake_shift:
        d["brake"] = np.interp(pos + brake_shift, pos, d["brake"].to_numpy(float))
    if thr_shift:
        d["throttle"] = np.interp(pos - thr_shift, pos, d["throttle"].to_numpy(float))
    d["lat_g"] = (d["ang_y"] * d["speed_kmh"] / 3.6 / 9.81).clip(-4, 4)
    return d


